"""Writes app/src/main/res/drawable/ic_launcher_foreground.xml: a symmetric leaf inside a 3/4 progress ring.

The leaf lies on the 45-degree diagonal (tip up-right). Its center can be nudged with (dx, dy) to balance the
ring's gold arc, whose weight sits down-right. The vein is cut out of the leaf (evenOdd), so it shows in the
single-color themed icon too, where a painted vein would vanish.

Usage: python make_fg.py [<out.xml> <length> <halfwidth> <dx> <dy> [base_round base_wide tip_pull tip_wide]]
With no arguments it writes the app's icon with the values in use (see "App icon" in DEVELOPER.md).
Check the result with centroid.py (visual balance) and render.py (a PNG preview).
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "..", "app", "src", "main", "res", "drawable", "ic_launcher_foreground.xml")
# The values in use: chosen 2026-10-19 so the visual center lands within 0.2% of the icon's center.
DEFAULTS = ["30", "8.5", "-1.6", "-3.6", "0.0", "1.20", "0.25", "1.10"]
TRACK_ALPHA = 0.4

args = sys.argv[1:] or [DEFAULT_OUT, *DEFAULTS]
out, length, half, dx, dy = args[0], *map(float, args[1:5])
# Leaf shape: how far along the axis the base's control point sits (0 = a fully rounded base), how wide it
# pulls, and the same for the tip's control point (larger tip_pull = a longer, sharper tip).
base_round, base_wide, tip_pull, tip_wide = map(float, args[5:9] if len(args) > 8 else DEFAULTS[4:])
cx, cy = 54 + dx, 54 + dy
ux, uy = math.cos(math.radians(-45)), math.sin(math.radians(-45))  # along the leaf, base -> tip (up-right)
vx, vy = -uy, ux  # across the leaf


def pt(u, v):
    """Leaf-local (u from the leaf's middle along its axis, v across) -> icon coordinates."""
    return cx + u * ux + v * vx, cy + u * uy + v * vy


def f(p):
    return f"{p[0]:.2f},{p[1]:.2f}"


L, W = length, half
base, tip = pt(-L / 2, 0), pt(L / 2, 0)
# Two mirrored cubics: a rounded base and a pointed tip. Control points tuned so the widest point
# is a little below the middle, like a real leaf.
c1a, c1b = pt(-L / 2 + base_round * L, base_wide * W), pt(L / 2 - tip_pull * L, tip_wide * W)
c2a, c2b = pt(L / 2 - tip_pull * L, -tip_wide * W), pt(-L / 2 + base_round * L, -base_wide * W)
leaf = f"M{f(base)} C{f(c1a)} {f(c1b)} {f(tip)} C{f(c2a)} {f(c2b)} {f(base)} Z"

# Midrib: a thin capsule from near the base to about two-thirds of the way to the tip, cut out of the leaf.
r = 0.95
v0, v1 = -L / 2 + 0.16 * L, L / 2 - 0.30 * L
a, b, c, d = pt(v0, r), pt(v1, r), pt(v1, -r), pt(v0, -r)
vein = f"M{f(a)} L{f(b)} A{r},{r} 0 0,0 {f(c)} L{f(d)} A{r},{r} 0 0,0 {f(a)} Z"

# Stem: continues the axis out of the base, short enough to stay well inside the ring (inner edge at 21).
stem_end = pt(-L / 2 - 3.2, 0)
stem_start = pt(-L / 2 + 1.0, 0)

xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!--
  Launcher icon: a leaf inside a three-quarters-full progress ring, like the goal rings on the Today
  screen. Everything stays inside the 66dp safe zone (radius 33 around the center), so no launcher mask
  crops it. Also used as the monochrome (themed) icon, which is why the vein is cut out of the leaf
  (evenOdd) rather than painted: a themed icon draws every path in one color.
  The leaf sits slightly up-left of center ({dx:+.1f}, {dy:+.1f}) to balance the gold arc, whose weight is
  down-right; the visual center lands on the icon's center. Generated by tools/icon/make_fg.py; edit and
  rerun that instead of this file (see "App icon" in DEVELOPER.md).
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- Ring track -->
    <path
        android:pathData="M54,30 A24,24 0 1,1 54,78 A24,24 0 1,1 54,30"
        android:strokeWidth="6"
        android:strokeColor="#FFFFFF"
        android:strokeAlpha="{TRACK_ALPHA}" />
    <!-- Ring progress: 270 degrees, clockwise from the top -->
    <path
        android:pathData="M54,30 A24,24 0 1,1 30,54"
        android:strokeWidth="6"
        android:strokeColor="#F2C66D"
        android:strokeLineCap="round" />
    <!-- Stem -->
    <path
        android:pathData="M{f(stem_start)} L{f(stem_end)}"
        android:strokeWidth="2.4"
        android:strokeColor="#FFFFFF"
        android:strokeLineCap="round" />
    <!-- Leaf, with the vein cut out -->
    <path
        android:fillColor="#FFFFFF"
        android:fillType="evenOdd"
        android:pathData="{leaf} {vein}" />
</vector>
"""
open(out, "w", encoding="utf-8", newline="\n").write(xml)
print(f"stem end is {math.dist(stem_end, (54, 54)) + 1.2:.1f} from the center (ring inner edge: 21)")
print(f"tip is {math.dist(tip, (54, 54)):.1f} from the center")
